CREATE OR REPLACE FUNCTION fn_usbd30_facilities_silos_sem_warehouses
RETURN SYS_REFCURSOR
IS
  v_cur SYS_REFCURSOR;
BEGIN
  OPEN v_cur FOR
    SELECT DISTINCT
           FACILITY.FACILITY_ID,
           FACILITY.NAME,
           FACILITY_TYPE.NAME
    FROM   FACILITY
           JOIN FACILITY_TYPE
             ON FACILITY_TYPE.TYPE_ID = FACILITY.FACILITY_TYPETYPE_ID
           JOIN BUILDING
             ON BUILDING.FACILITYFACILITY_ID = FACILITY.FACILITY_ID
           JOIN BUILDINGTYPE
             ON BUILDINGTYPE.ID = BUILDING.BUILDINGTYPEID
    WHERE  UPPER(BUILDINGTYPE.NAME) = 'SILO'
      AND  NOT EXISTS (
             SELECT 1
             FROM   BUILDING b_w
                    JOIN BUILDINGTYPE bt_w
                      ON bt_w.ID = b_w.BUILDINGTYPEID
             WHERE  b_w.FACILITYFACILITY_ID = FACILITY.FACILITY_ID
               AND  UPPER(bt_w.NAME) = 'WAREHOUSE'
           )
    ORDER BY FACILITY.FACILITY_ID;

  RETURN v_cur;

EXCEPTION
  WHEN OTHERS THEN
    -- Em erro, devolve cursor vazio (padrão das aulas)
    OPEN v_cur FOR SELECT 1 AS dummy FROM dual WHERE 1 = 0;
    RETURN v_cur;
END;
/
