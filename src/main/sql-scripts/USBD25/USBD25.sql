CREATE OR REPLACE FUNCTION FUNCTION_USBD25_LIST_FACILITIES_WITHOUT_STOP
    RETURN SYS_REFCURSOR
AS
    c_result SYS_REFCURSOR;
    train_id NUMBER;
BEGIN
    -- Selecionar o comboio mais recente pela data e hora
SELECT TRAIN_ID
INTO train_id
FROM TRAIN
ORDER BY TO_DATE(DATE_D, 'DD/MM/YYYY') DESC, TIME_T DESC
    FETCH FIRST 1 ROWS ONLY;


OPEN c_result FOR
SELECT
    FACILITY.FACILITY_ID,
    FACILITY.NAME,
    TRAIN_ROUTE."ORDER"
FROM TRAIN_ROUTE
         JOIN FACILITY
              ON FACILITY.FACILITY_ID = TRAIN_ROUTE.FACILITY_ID
         LEFT JOIN BUILDING
                   ON BUILDING.FACILITYFACILITY_ID = FACILITY.FACILITY_ID
WHERE TRAIN_ROUTE.TRAIN_ID = train_id
  AND BUILDING.ID IS NULL
ORDER BY TRAIN_ROUTE."ORDER";

RETURN c_result;
END;
/
